#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes docs/backfill/register-scope.adoc (spd#149): per register, where replay starts today
# (seed issue and path, earliest and latest issue with actions) and the gap to № 1.
#
#   ruby scripts/register_scope_report.rb [--root DIR] [--out FILE]
#
# Reads catalogs/registers.yaml through Ituob::Catalogs::Registers, ob-issues/<n>/<slug>/
# for actions and docs/backfill/inventory.yaml for absent numbers (class not a).
# Output carries no wall-clock value, so a rerun is byte-identical.

require 'fileutils'
require 'optparse'
require 'yaml'
require 'ituob'
require 'ituob/support'
require 'ituob/catalogs'

module RegisterScopeReport
  OUT_PATH = 'docs/backfill/register-scope.adoc'
  INVENTORY_PATH = 'docs/backfill/inventory.yaml'
  COLUMNS = ['Register', 'Slug', 'Seed issue', 'Seed path', 'Seed includes seed issue',
             'Earliest action issue', 'Latest action issue', 'Gap to № 1', 'Absent before seed'].freeze

  Row = Struct.new(:register_id, :slug, :seed_issue, :seed_path, :seed_includes_seed_issue,
                   :earliest_action, :latest_action, :absent_before_seed, keyword_init: true) do
    # First issue the replay can use: the seed issue, else the earliest action.
    def start_issue = seed_issue || earliest_action

    def gap_to_first = start_issue && (start_issue - 1)
  end

  # Real actions are NNN-TYPE.yaml; text.yaml is a TextAmendment, not an action.
  ACTION_FILE = /\A\d+-[A-Z0-9_]+\.yaml\z/i

  module_function

  # nil when the inventory file is missing: the answer is unknown, not "none".
  def absent_numbers(root)
    path = File.join(root, INVENTORY_PATH)
    return nil unless File.exist?(path)

    YAML.safe_load_file(path, permitted_classes: [Date, Time])['inventory']
        .reject { |e| e['class'] == 'a' }.map { |e| e['number'] }.sort
  end

  # Issue numbers holding at least one action file for the register's amendment slug.
  def action_issues(root, slug)
    Dir.glob(File.join(root, 'ob-issues', '*', slug, '*.yaml')).filter_map do |p|
      next unless File.basename(p).match?(ACTION_FILE)

      number = File.basename(File.dirname(File.dirname(p)))
      number.to_i if number.match?(/\A\d+\z/)
    end.uniq.sort
  end

  def rows(root, catalog_path: File.join(root, 'catalogs', 'registers.yaml'))
    Ituob::Catalogs::Registers.load!(path: catalog_path)
    absent = absent_numbers(root)
    Ituob::Catalogs::Registers.all.map do |entry|
      issues = action_issues(root, entry.amendment_slug)
      Row.new(register_id: entry.register_id, slug: entry.amendment_slug,
              seed_issue: entry.seed_issue, seed_path: entry.seed_path,
              seed_includes_seed_issue: entry.seed_includes_seed_issue,
              earliest_action: issues.first, latest_action: issues.last,
              absent_before_seed: (absent.any? { |n| n < entry.seed_issue } if absent && entry.seed_issue))
    end
  end

  def cell(value) = value.nil? ? '—' : value.to_s.gsub('|', '\|')

  def table_row(row)
    cells = [row.register_id, row.slug, row.seed_issue, row.seed_path, row.seed_includes_seed_issue,
             row.earliest_action, row.latest_action, row.gap_to_first, row.absent_before_seed]
    "| #{cells.map { |c| cell(c) }.join(' | ')}"
  end

  def adoc(rows)
    <<~ADOC
      = Register scope baseline (#149)
      :toc:

      // Generated by scripts/register_scope_report.rb; do not edit by hand.

      How far back each register's replay starts today. The gap to № 1 counts the issues
      before the seed issue (or, for a register with no seed, before its earliest action).
      "Absent before seed" is true when an inventory number below the seed issue is not class a.

      [cols="#{Array.new(COLUMNS.size, 1).join(',')}",options="header"]
      |===
      #{COLUMNS.map { |c| "| #{c}" }.join("\n")}

      #{rows.map { |r| table_row(r) }.join("\n\n")}
      |===

      == Decisions still open

      For the follow-on register scope decision card:

      * Era seeds: whether a register whose seed is a printed consolidated list (not a
        replayed dataset) should be seeded from that list at its issue, and which issue.
      * Registers that may predate all sources: whether a register whose earliest known
        issue is later than № 1 starts there or needs a pre-corpus seed.
      * Registers with no seed issue, or with no actions in ob-issues: whether they are in scope.
    ADOC
  end

  def main(argv)
    root = File.expand_path('..', __dir__)
    out = nil
    OptionParser.new do |o|
      o.on('--root DIR') { |v| root = File.expand_path(v) }
      o.on('--out FILE') { |v| out = v }
    end.parse!(argv)
    path = out || File.join(root, OUT_PATH)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, adoc(rows(root)))
  end
end

RegisterScopeReport.main(ARGV) if $PROGRAM_NAME == __FILE__
