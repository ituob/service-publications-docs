#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes docs/backfill/inventory.yaml (spd#149): one entry per OB number 1-1343 with
# its class, expected year and local evidence.
#
#   ruby scripts/build_backfill_inventory.rb [--root DIR] [--out FILE]
#
# Class (a) is a numeric ob-issues/<n>/ directory with meta.yaml; every other number
# is 'unresolved'. Output carries no wall-clock value, so a rerun is byte-identical.

require 'fileutils'
require 'optparse'
require 'yaml'
require_relative 'backfill/inventory'

module BuildBackfillInventory
  OUT_PATH = 'docs/backfill/inventory.yaml'
  REFERENCE_DOC = /\AT-SP-OB\.(\d+)-/
  HEADER = <<~TEXT
    # Generated by scripts/build_backfill_inventory.rb; do not edit by hand.
    # class: a = held in ob-issues/; unresolved = no evidence yet (b/c/d need evidence).
  TEXT

  module_function

  def held_issues(root)
    Dir.glob(File.join(root, 'ob-issues', '*', 'meta.yaml')).each_with_object({}) do |path, h|
      number = File.basename(File.dirname(path))
      next unless number.match?(/\A\d+\z/)

      h[number.to_i] = File.read(path)[/^publication_date:\s*(\S+)/, 1]
    end
  end

  def reference_numbers(root)
    Dir.glob(File.join(root, 'itu-ob-data', 'reference-docs', '*')).filter_map do |p|
      File.basename(p)[REFERENCE_DOC, 1]&.to_i
    end.uniq.sort
  end

  def build(root)
    held = held_issues(root).select { |n, _| n.between?(Backfill::Inventory::FIRST, Backfill::Inventory::LAST) }
    entries = Backfill::Inventory.classify(held, reference_docs: reference_numbers(root))
    HEADER + { 'inventory' => entries }.to_yaml
  end

  def main(argv)
    root = File.expand_path('..', __dir__)
    out = nil
    OptionParser.new do |o|
      o.on('--root DIR') { |v| root = File.expand_path(v) }
      o.on('--out FILE') { |v| out = v }
    end.parse!(argv)
    path = out || File.join(root, OUT_PATH)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, build(root))
  end
end

BuildBackfillInventory.main(ARGV) if $PROGRAM_NAME == __FILE__
